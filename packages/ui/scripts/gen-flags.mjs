// The flags of pdx-flag (#1091): one module per region, and the loader map pdx-flag reads.
//
//   src/flag/flags/<xx>.ts    `export default '<svg>'`, the 4:3 flag of region XX
//   src/flag/flag-loaders.ts  region → `() => import('./flags/<xx>')`, written from the modules
//
// The drawings are flag-icons' (https://github.com/lipis/flag-icons), MIT, © 2013 Panayiotis Lipiridis;
// licenses/THIRD-PARTY.md carries the licence. They are taken once, not depended on: no package of the
// repository installs flag-icons. To take them again (a new release, a corrected flag):
//
//   npm pack flag-icons@<version> --pack-destination <dir>   (outside the repository)
//   tar -xzf <dir>/flag-icons-<version>.tgz -C <dir>
//   node packages/ui/scripts/gen-flags.mjs --from <dir>/package/flags/4x3
//
// Only regions: the two-letter files, which are BCP 47 region subtags (`it`, `gb`, `eu`). Sub-national
// flags (`gb-eng`, `es-ct`) and groupings (`arab`, `asean`) are not a culture's region. The root's
// `id` is dropped and the space between tags collapsed; the rest is the drawing as published. A flag is
// drawn as an <img> from a data URL, so the ids inside one never meet another's.
//
// Without `--from`, the loader map is written again from the modules there are; `--check` writes
// nothing and exits 1 when the map does not list exactly the modules, which is what the drift test runs.

import { readFileSync, writeFileSync, readdirSync, mkdirSync, rmSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const FLAG_DIR = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'flag');
const MODULE_DIR = join(FLAG_DIR, 'flags');
const LOADERS = join(FLAG_DIR, 'flag-loaders.ts');
const MODULE_HEADER = '// Generated by packages/ui/scripts/gen-flags.mjs from flag-icons (MIT, © 2013 Panayiotis Lipiridis) — do not edit.\n';
const LOADER_HEADER = '// Generated by packages/ui/scripts/gen-flags.mjs from src/flag/flags/ — do not edit.\n';

/** A region subtag of two letters, the file name of its flag; `xx` is flag-icons' blank, not a region. */
const REGION = /^(?!xx$)[a-z]{2}$/;

/** A flag's SVG as a module holds it: its root `id` gone, the space between tags collapsed. */
export function compactSvg(svg) {
    return svg.replace(/<svg([^>]*?)\s+id="[^"]*"/, '<svg$1').replace(/>\s+</g, '><').trim();
}

/** The loader map's text, from the regions there are modules for. */
export function loaderText(regions) {
    const entries = [...regions].sort().map((r) => `    ${r}: () => import('./flags/${r}'),`).join('\n');
    return `${LOADER_HEADER}// Every region pdx-flag can draw: the import that loads its flag, for the component to call when the\n`
        + `// region is shown. Written out, not an import over a variable, so every bundler sees each chunk.\n\n`
        + `export const FLAG_LOADERS: Record<string, () => Promise<{ default: string }>> = {\n${entries}\n};\n`;
}

/** The regions there are modules for. */
function moduleRegions() {
    return existsSync(MODULE_DIR) ? readdirSync(MODULE_DIR).filter((f) => f.endsWith('.ts')).map((f) => f.slice(0, -3)) : [];
}

function main() {
    const args = process.argv.slice(2);
    const fromAt = args.indexOf('--from');
    if (fromAt >= 0) {
        const from = args[fromAt + 1];
        if (!from || !existsSync(from)) throw new Error(`[gen-flags] --from needs flag-icons' flags/4x3 folder; "${from}" is not there`);
        const files = readdirSync(from).filter((f) => f.endsWith('.svg') && REGION.test(f.slice(0, -4)));
        mkdirSync(MODULE_DIR, { recursive: true });
        for (const r of moduleRegions()) rmSync(join(MODULE_DIR, `${r}.ts`));
        for (const f of files) {
            const svg = compactSvg(readFileSync(join(from, f), 'utf8'));
            if (!svg.startsWith('<svg') || /<script|\son\w+=/i.test(svg)) throw new Error(`[gen-flags] ${f} is not a plain SVG drawing`);
            writeFileSync(join(MODULE_DIR, `${f.slice(0, -4)}.ts`), `${MODULE_HEADER}export default ${JSON.stringify(svg)};\n`);
        }
        console.log(`[gen-flags] ${files.length} flags from ${from}.`);
    }
    const text = loaderText(moduleRegions());
    const current = existsSync(LOADERS) ? readFileSync(LOADERS, 'utf8') : '';
    if (args.includes('--check')) {
        if (current !== text) {
            console.error('[gen-flags] the loader map does not list exactly the flag modules. Run: node packages/ui/scripts/gen-flags.mjs');
            process.exit(1);
        }
        console.log(`[gen-flags] ${moduleRegions().length} flag modules and the loader map are current.`);
        return;
    }
    if (current !== text) writeFileSync(LOADERS, text);
    console.log(`[gen-flags] the loader map lists ${moduleRegions().length} regions.`);
}

// Only when run as a script: importing this file (a test does) must not write anything.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
