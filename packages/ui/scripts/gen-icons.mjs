// Write one module per icon of the «pragmatic» set, and the loader map the resolver reads (#47).
//
//   src/icon/pragmatic-icon-data.ts   the SVG of every icon (the source; edited by hand)
//   → src/icon/pragmatic/<name>.ts    `export default '<svg>'` — what `@pdxui/ui/icons/<name>` is
//   → src/icon/pragmatic-loaders.ts   name → `() => import('./pragmatic/<name>')`, for names from data
//
// A page imports the icons it draws instead of the whole set: the compiler imports the ones a template
// names, a component imports its fixed ones, and the resolver loads the rest on demand, each as its own
// small chunk. The loader map is written out, not a dynamic import over a variable, so every bundler
// sees each chunk, from the sources and from dist alike.
//
// An icon module is DATA, with no import of its own, and whoever imports it registers it
// (`defineIcons({ check })`). A module that registered itself would import the shared map, and Rollup
// puts that map in some shared chunk: measured on the showcase, every icon chunk then imported the
// chunk of pdx-icon, the core and pdx-dropdown-menu, and each entry of the loader map carried that
// preload list — 9.9 KB gzip for the chunk that holds the map.
//
// `node scripts/gen-icons.mjs` rewrites both; `--check` writes nothing and exits 1 when a file differs,
// which is what the drift test runs.

import { readFileSync, writeFileSync, readdirSync, mkdirSync, rmSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

// A path string, not `new URL(…, import.meta.url)`: under a DOM test environment `URL` is the DOM's,
// which `fileURLToPath` refuses.
const ICON_DIR = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'icon');
const MODULE_DIR = join(ICON_DIR, 'pragmatic');
const LOADERS = join(ICON_DIR, 'pragmatic-loaders.ts');
const HEADER = '// Generated by packages/ui/scripts/gen-icons.mjs from src/icon/pragmatic-icon-data.ts — do not edit.\n';

/** An icon name that is a safe file name and import specifier. */
const NAME = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

/** The files the set generates, by path, from the icons by name. */
export function iconFiles(svgs) {
    const names = Object.keys(svgs).sort();
    const bad = names.filter(n => !NAME.test(n));
    if (bad.length) throw new Error(`[gen-icons] icon names that are not kebab-case: ${bad.join(', ')}`);
    const files = new Map();
    for (const name of names) {
        files.set(join(MODULE_DIR, `${name}.ts`), `${HEADER}export default ${JSON.stringify(svgs[name])};\n`);
    }
    const entries = names.map(n => `    ${JSON.stringify(n)}: () => import('./pragmatic/${n}'),`).join('\n');
    files.set(LOADERS, `${HEADER}// Every icon of the «pragmatic» set, by name: the import that loads it, for the resolver to call when\n`
        + `// a name the page does not have yet is drawn.\n\n`
        + `export const PRAGMATIC_LOADERS: Record<string, () => Promise<{ default: string }>> = {\n${entries}\n};\n`);
    return files;
}

async function main() {
    const check = process.argv.includes('--check');
    const { PRAGMATIC_SVGS } = await import(pathToFileURL(join(ICON_DIR, 'pragmatic-icon-data.ts')).href);
    const files = iconFiles(PRAGMATIC_SVGS);
    const stale = existsSync(MODULE_DIR)
        ? readdirSync(MODULE_DIR).map(f => join(MODULE_DIR, f)).filter(p => !files.has(p))
        : [];
    const differ = [...files].filter(([p, text]) => !existsSync(p) || readFileSync(p, 'utf8') !== text).map(([p]) => p);
    if (check) {
        if (differ.length || stale.length) {
            console.error(`[gen-icons] out of date: ${differ.length} file(s) differ, ${stale.length} stale. Run: pnpm --dir packages/ui run icons`);
            process.exit(1);
        }
        console.log(`[gen-icons] ${files.size - 1} icon modules and the loader map are current.`);
        return;
    }
    mkdirSync(MODULE_DIR, { recursive: true });
    for (const p of stale) rmSync(p);
    for (const p of differ) writeFileSync(p, files.get(p));
    console.log(`[gen-icons] ${files.size - 1} icons: wrote ${differ.length} file(s), removed ${stale.length}.`);
}

// Only when run as a script: importing this file (a test does) must not write anything.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await main();
