// Ports showcase component pages into the site as reusable demo galleries.
// Each packages/compiler/demo/showcase-new/pages/comp-*.pdx becomes src/demos/comp-*.pdx,
// stripped of @page/@title (so it registers as a plain custom element <pdx-comp-NAME>,
// not a route). The site renders that element inside the component page - full, reactive
// demos with zero re-authoring, always in sync with the showcase content.

import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync, unlinkSync, rmSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const here = dirname(fileURLToPath(import.meta.url));
const SRC = join(here, '../../compiler/demo/showcase-new/pages');
const OUT = join(here, '../src/demos');
// Pages written FOR the site, because the component has no showcase page to port — pdx-calendar,
// pdx-json-editor, pdx-page-header, pdx-relation-picker. They live in a committed directory of
// their own, not in OUT: a hand-written file inside a generated, uncommitted directory is
// distinguishable only by a banner and is easily lost. The routes read them from it, and this
// script is the ONLY writer of OUT.
const AUTHORED = join(here, '../src/demos-authored');

if (!existsSync(OUT)) mkdirSync(OUT, { recursive: true });
// Rewritten whole on every run: a section renamed or moved in the showcase leaves no stale copy.
const OUT_SECTIONS = join(OUT, 'sections');
rmSync(OUT_SECTIONS, { recursive: true, force: true });

// Port both component galleries (comp-*) and the pure-CSS design pages (design-*).
const files = readdirSync(SRC).filter(f => (f.startsWith('comp-') || f.startsWith('design-')) && f.endsWith('.pdx'));
let ported = 0;
const index = [];
const designIndex = [];

for (const f of files) {
    let code = readFileSync(join(SRC, f), 'utf8');
    // Strip route metadata so importing the file does NOT register a route.
    code = code.replace(/^[ \t]*@page\b.*$\n?/gm, '');
    code = code.replace(/^[ \t]*@title\b.*$\n?/gm, '');
    // Many showcase pages relied on @page/@title alone for new-mode detection. Stripping it would
    // drop them to legacy mode -> no auto-return -> top-level consts aren't exposed to ctx, so
    // bindings like :data="rows" arrive empty (e.g. data-grid). Restore the original (new) mode
    // with a harmless dummy signal when no other new-mode marker remains.
    if (!/\$signal\(|\$derived\(|\$store\(|\$effect\(|\$watch\(|@prop |@event |@fetch |@form |@expose |@provide |@inject |@store /.test(code)) {
        code = code.replace(/(<script setup>)/, '$1\nlet _pdxKeep = $signal(0);');
    }
    // No syntax rewriting here: translating raw `${…}` bindings into `:attr=` / `{{ }}` would let
    // the site compile clean while the showcase pages it ports teach the form the compiler warns
    // against (PDX_RAW_INTERPOLATION). The pages are written in the supported syntax, and
    // compiler/tests/showcase-warnings.test.ts keeps them so.
    // Header note: generated, do not edit by hand.
    const banner = `<!-- GENERATED by scripts/port-demos.mjs from showcase-new/pages/${f}. Do not edit. -->\n`;
    writeFileSync(join(OUT, f), banner + code, 'utf8');
    // The sections the page composes, and the state they share: copied beside it, so the
    // site's resolver finds `pdx-demo-<page>-<slug>` under src/ as the showcase's finds it under pages/.
    const name = f.replace(/\.pdx$/, '');
    const sections = join(SRC, 'sections', name);
    if (existsSync(sections)) {
        mkdirSync(join(OUT_SECTIONS, name), { recursive: true });
        for (const s of readdirSync(sections).filter((x) => x.endsWith('.pdx') || x.endsWith('.pdx.ts'))) {
            const from = `showcase-new/pages/sections/${name}/${s}`;
            const head = s.endsWith('.pdx.ts')
                ? `// GENERATED by scripts/port-demos.mjs from ${from}. Do not edit.\n`
                : `<!-- GENERATED by scripts/port-demos.mjs from ${from}. Do not edit. -->\n`;
            writeFileSync(join(OUT_SECTIONS, name, s), head + readFileSync(join(sections, s), 'utf8'), 'utf8');
        }
    }
    if (f.startsWith('design-')) designIndex.push(f.replace(/^design-|\.pdx$/g, ''));
    else index.push(f.replace(/^comp-|\.pdx$/g, ''));
    ported++;
}

// NOT copied: the site's routes load them from their own directory. A copy in OUT would put a
// second file claiming `pdx-comp-calendar` (and the other three) under src/, and the component
// resolver would print PDX_TAG_COLLISION_RESOLVER for each at every build. They are listed in the
// index; a stale copy left in OUT is removed.
let authored = 0;
if (existsSync(AUTHORED)) {
    for (const f of readdirSync(AUTHORED).filter(x => x.endsWith('.pdx'))) {
        if (existsSync(join(OUT, f))) unlinkSync(join(OUT, f));
        if (f.startsWith('design-')) designIndex.push(f.replace(/^design-|\.pdx$/g, ''));
        else index.push(f.replace(/^comp-|\.pdx$/g, ''));
        authored++;
    }
}

writeFileSync(join(OUT, 'index.json'), JSON.stringify(index.sort(), null, 0), 'utf8');
writeFileSync(join(OUT, 'design-index.json'), JSON.stringify(designIndex.sort(), null, 0), 'utf8');
console.log(
    `Ported ${ported} pages -> src/demos/, ${authored} site-authored in src/demos-authored/ `
    + `(${index.length} comp, ${designIndex.length} design)`,
);
