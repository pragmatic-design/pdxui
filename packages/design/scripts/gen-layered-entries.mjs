// One importable entry per theme and per component, each landing in the right layer.
//
// An app that uses one theme should ship one theme: importing all thirteen costs 10.5 KB gzipped,
// 20% of the stylesheet, for rules it cannot reach — and it is render-blocking CSS.
//
// A sub-path cannot point at the RAW theme file, which carries no `@layer` of its own: it gets one
// from the `layer(pdx.themes)` on the import in `pragmatic-design.css`. Imported on its own it
// lands UNLAYERED, and unlayered CSS beats everything inside a layer — so taking the saving would
// silently reverse the design system's first promise, "Consumer's unlayered CSS always wins (zero
// !important needed)". `tests/one-theme.spec.ts` measures it.
//
// WHY A WRAPPER AND NOT AN `@layer` INSIDE EACH THEME: the theme files are read as TEXT by several
// suites — theme-contrast-shipped, theme-fidelity, theme-control-height, design-tokens, the
// builder's theme list. Wrapping their contents would put every one of those readers at risk to
// solve a packaging problem. The raw files stay as they are; each wrapper is a few lines of its own.
//
// The raw files stay internal: `base.css` and `pragmatic-design.css` import them with their
// `layer(...)`, and the package exports point HERE. `core/tests/design-exports.test.ts` holds both
// halves of that.

import { readdirSync, writeFileSync, mkdirSync, readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const THEMES = join(here, '..', 'src', 'themes');
const OUT = join(THEMES, 'layered');

/** The cascade, copied from base.css — the one place it is decided. */
const LAYER_ORDER = readFileSync(join(here, '..', 'src', 'base.css'), 'utf8')
    .split('\n')
    .find((l) => l.startsWith('@layer '));

if (!LAYER_ORDER) throw new Error('base.css no longer declares the layer order — this generator reads it from there');

const COMPONENTS = join(here, '..', 'src', 'components');
const COMPONENTS_OUT = join(COMPONENTS, 'layered');

/**
 * Files that belong to no single component: `.pdx-table`, `.pdx-nav`, `.pdx-code`, the alert and
 * badge classes. They are the CSS-only tier a developer applies to plain HTML, so they stay in
 * `base.css` and get no per-component entry. `drop-zone` paints the state core's
 * `useDropZone` writes on any element: no component owns it either.
 */
const SHARED = new Set(['code', 'drop-zone', 'feedback', 'nav', 'table']);

function entriesFor(dir, out, layer, only) {
    const names = readdirSync(dir)
        .filter((f) => f.endsWith('.css') && f !== '_all.css')
        .map((f) => f.replace(/\.css$/, ''))
        .filter((n) => (only ? only(n) : true))
        .sort();

    mkdirSync(out, { recursive: true });
    for (const name of names) {
        writeFileSync(join(out, `${name}.css`), `/* GENERATED by scripts/gen-layered-entries.mjs — do not edit. Edit ../${name}.css. */

/* The order first: a stylesheet imported on its own has to land in \`${layer}\`, and a layer used
   before it is declared takes its position from first use. Repeating the declaration is a no-op
   when base.css got there first — and NOT repeating it is how a file imported alone lands
   unlayered, which beats everything the design system ships. */
${LAYER_ORDER}

@import "../${name}.css" layer(${layer});
`);
    }
    return names.length;
}

const themes = entriesFor(THEMES, OUT, 'pdx.themes');
const components = entriesFor(COMPONENTS, COMPONENTS_OUT, 'pdx.components', (n) => !SHARED.has(n));

console.log(`[gen-layered-entries] ${themes} themes → src/themes/layered/, ${components} components → src/components/layered/`);
