/** Is this theme's gap in this family already judged deliberate? Returns the reason, or null. */
export function deliberateReason(theme, family) {
    return DELIBERATE.find((d) => d.theme === theme && d.family === family)?.why ?? null;
}

function main() {
    const coverage = themeCoverage();
    const { themes, contract, gaps, majority } = coverage;
    if (process.argv.includes('--emit')) {
        const out = fileURLToPath(new URL('../src/engine/theme-contract.ts', import.meta.url));
        writeFileSync(out, contractModuleSource(coverage));
        console.log(`[theme-coverage] wrote src/engine/theme-contract.ts — ${contract.length} contract tokens, ${gaps.size} themes.`);
        return;
    }
    if (process.argv.includes('--json')) {
        console.log(JSON.stringify({ contract, gaps: Object.fromEntries(gaps) }, null, 2));
        return;
    }
    console.log(`[theme-coverage] ${themes.length} themes, ${contract.length} tokens in the contract (set by ${majority} or more).`);
    console.log(`'${BASE_THEME}' is the base and is not reported: what it leaves alone is what tokens.css carries.\n`);

    const ordered = [...gaps.entries()].sort((a, b) => a[1].length - b[1].length);
    let decisions = 0;
    let settled = 0;
    for (const [theme, missing] of ordered) {
        console.log(`  ${theme.padEnd(16)} inherits ${String(missing.length).padStart(2)}`);
        if (!missing.length) continue;

        // One line per FAMILY, not per token: inside a family the answer is the same.
        const byFamily = new Map();
        for (const token of missing) {
            const fam = familyOf(token);
            const key = fam ? fam.name : token;
            if (!byFamily.has(key)) byFamily.set(key, { fam, tokens: [] });
            byFamily.get(key).tokens.push(token);
        }
        const open = [];
        for (const [key, entry] of byFamily) {
            const why = deliberateReason(theme, key);
            if (why) { settled++; continue; }
            decisions++;
            open.push([key, entry]);
        }
        if (!open.length) { console.log('    all judged deliberate'); continue; }
        for (const [key, entry] of open) {
            const count = entry.tokens.length > 1 ? ` (${entry.tokens.length} tokens)` : '';
            console.log(`    ${key}${count}`);
            if (entry.fam) {
                console.log(`      ? ${entry.fam.question}`);
                console.log(entry.fam.see
                    ? `      look at: ${entry.fam.see} [${theme}]`
                    : '      no baseline shows this - judgement without a picture, or write a scenario first');
            }
        }
    }
    const total = [...gaps.values()].reduce((n, m) => n + m.length, 0);
    console.log(`\n${total} gaps in ${settled + decisions} decisions.`);
    console.log(`${settled} judged deliberate on 2026-09-07 — each carries its reason in DELIBERATE, and`);
    console.log('each was looked at in a committed baseline before being written there.');
    console.log(decisions
        ? `${decisions} still open, listed above.`
        : 'Nothing open. A theme that changes its mind removes its DELIBERATE line and reappears here.');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
