// The tags that need no import (#991): src/no-import-tags.generated.ts, the list
// ComponentResolver.knownWithoutImport reads.
//
// They are the `pdx-` element selectors of the design system's CSS and the `component('pdx-…')` /
// `define('pdx-…')` calls in the other @pdxui packages' sources: fixed by the sources of a release.
// The resolver used to walk those sources for them, 1,687 files read synchronously in every process
// that asked, and the walk timed the gate out three times (#716, #991). This script walks them once,
// with the same scanner (src/no-import-tags.ts), and writes the answer down.
//
//   node packages/compiler/scripts/gen-no-import-tags.mjs           write the list
//   node packages/compiler/scripts/gen-no-import-tags.mjs --check   exit 1 if it is not current
//
// Run it after a package adds or drops a tag; tests/no-import-tags-generated.test.ts fails until then.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { scanNoImportTags } from '../src/no-import-tags.ts';

const SRC = join(dirname(fileURLToPath(import.meta.url)), '..', 'src');
const OUT = join(SRC, 'no-import-tags.generated.ts');

/** The module's text, from the tags walked. */
export function generatedText(tags) {
    const lines = [...tags].sort().map((t) => `    '${t}',`).join('\n');
    return '// Generated by packages/compiler/scripts/gen-no-import-tags.mjs from the @pdxui packages\' sources — do not edit.\n'
        + '// The `pdx-` tags that need no import: element selectors of the design system, and custom elements\n'
        + '// another @pdxui package defines. ComponentResolver.knownWithoutImport reads it (#991).\n\n'
        + `export const NO_IMPORT_TAGS: readonly string[] = [\n${lines}\n];\n`;
}

function main() {
    const text = generatedText(scanNoImportTags(SRC));
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (process.argv.includes('--check')) {
        if (current !== text) {
            console.error('[gen-no-import-tags] the list is not the sources\'. Run: node packages/compiler/scripts/gen-no-import-tags.mjs');
            process.exit(1);
        }
        console.log('[gen-no-import-tags] the list is current.');
        return;
    }
    if (current !== text) writeFileSync(OUT, text);
    console.log(`[gen-no-import-tags] ${text.split('\n').filter((l) => l.startsWith("    '")).length} tags → src/no-import-tags.generated.ts`);
}

main();
