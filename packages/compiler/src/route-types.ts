// `.pdx/routes.d.ts` (#150): the app's routes as types, for `navigate()` and `<pdx-link>`.
//
// The build and the dev server write it from the scanned `@page` patterns. It augments
// `@pdxui/router`'s `RouteRegistry` with one key per pattern — written without its constraints,
// `/users/:id`, the form `navigate('/users/:id', { id })` takes — and the pattern's params, typed
// from those constraints: `:id(number)` is a `number`, every other constraint and an unconstrained
// param a `string`. A pattern with a `*` is left out: its rest has no name to pass, and a URL into it
// goes through `navigate.url()`. The editor and `pdx check --types` read the file; an app's
// tsconfig includes it for its `.ts` modules.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'fs';
import { join, resolve } from 'path';
import { scanForRoutes, type ScannedRoute } from './plugin-utils';

/** The generated file, relative to the app's root. */
export const ROUTE_TYPES_FILE = '.pdx/routes.d.ts';

interface PatternPart {
    /** Literal text, or the param's name. */
    text: string;
    /** Set on a param: its constraint, `''` when it has none. */
    constraint?: string;
}

/** `\w`, one character at a time — the router's matcher reads a param's name the same way. */
const isWord = (c: string | undefined): boolean => c !== undefined && /\w/.test(c);

/**
 * `pattern` as literal text and params, in one left-to-right scan: `:id`, `:id(number)`. Scanned,
 * not matched with a regex: a regex for a param and its optional `(…)` runs in polynomial time on a
 * pattern of repeated `:A((`, as the router's matcher found (#67). The constraint ends at the first `)`,
 * as the matcher reads it.
 */
function patternParts(pattern: string): PatternPart[] {
    const parts: PatternPart[] = [];
    let literal = '';
    let i = 0;
    while (i < pattern.length) {
        if (pattern[i] === ':' && isWord(pattern[i + 1])) {
            let end = i + 1;
            while (isWord(pattern[end])) end++;
            const name = pattern.slice(i + 1, end);
            let constraint = '';
            if (pattern[end] === '(') {
                const close = pattern.indexOf(')', end + 1);
                if (close > end) { constraint = pattern.slice(end + 1, close); end = close + 1; }
            }
            if (literal) { parts.push({ text: literal }); literal = ''; }
            parts.push({ text: name, constraint });
            i = end;
            continue;
        }
        literal += pattern[i];
        i++;
    }
    if (literal) parts.push({ text: literal });
    return parts;
}

/** `/users/:id(number)` → `/users/:id`: the key `navigate()` is called with. */
export function routeKey(pattern: string): string {
    return patternParts(pattern).map((p) => (p.constraint === undefined ? p.text : `:${p.text}`)).join('');
}

/** The params of `pattern` as a TypeScript object type: `{ id: number; slug: string }`, or `{}`. */
export function routeParamsType(pattern: string): string {
    const fields = patternParts(pattern).filter((p) => p.constraint !== undefined)
        .map((p) => `${p.text}: ${p.constraint === 'number' ? 'number' : 'string'}`);
    return fields.length ? `{ ${fields.join('; ')} }` : '{}';
}

/** The text of `.pdx/routes.d.ts` for these route patterns. */
export function routeTypesDts(patterns: readonly string[]): string {
    const entries = new Map<string, string>();
    for (const pattern of patterns) {
        if (pattern.includes('*')) continue;
        entries.set(routeKey(pattern), routeParamsType(pattern));
    }
    const rows = [...entries].sort(([a], [b]) => a.localeCompare(b))
        .map(([key, params]) => `        ${JSON.stringify(key)}: ${params};`);
    return [
        '// Generated by @pdxui/compiler from the app\'s @page routes (#150). Do not edit: it is rewritten',
        '// when a route changes. `navigate()` and `<pdx-link>` are typed against it.',
        "import '@pdxui/router';",
        '',
        "declare module '@pdxui/router' {",
        '    interface RouteRegistry {',
        ...rows,
        '    }',
        '}',
        '',
    ].join('\n');
}

/**
 * The project's route keys (`/users/:id`), scanned as the build scans them — `src/` and `pages/`
 * under `root` — and in `dirs` too: what `pdx migrate` tells a pattern from a concrete URL by.
 */
export function projectRoutePatterns(root: string, dirs: readonly string[] = []): string[] {
    const routes: ScannedRoute[] = [];
    for (const dir of ['src', 'pages', ...dirs]) scanForRoutes(resolve(root, dir), routes);
    return [...new Set(routes.map((r) => routeKey(r.path)))];
}

/**
 * Write `.pdx/routes.d.ts` under `root` for these patterns, only when its text changes: a rewrite of
 * the same text would wake every watcher of the file for nothing. Returns whether it wrote.
 */
export function writeRouteTypes(root: string, patterns: readonly string[]): boolean {
    const file = join(root, ROUTE_TYPES_FILE);
    const text = routeTypesDts(patterns);
    if (existsSync(file) && readFileSync(file, 'utf-8') === text) return false;
    mkdirSync(join(root, '.pdx'), { recursive: true });
    writeFileSync(file, text);
    return true;
}
